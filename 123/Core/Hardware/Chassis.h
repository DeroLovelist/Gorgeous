/* =====================================================================
 * Chassis 底盘运动控制模块 (麦克纳姆轮)
 * ---------------------------------------------------------------------
 * 依赖:
 *   - motor.c   : Motor_Init() / Set_PWM(n, pwm)   (PWM 与方向)
 *   - ENCODER.c : Encoder_GetDelta(n)              (编码器增量)
 *   - pid.c     : 串级 PID + 转向 PID
 *   - JY61P     : 航向角 (仅转向闭环用, 由 Chassis_SetYawSource 注入)
 *
 * 车轮布局 (车头向前, 从底面向上看):
 *
 *        车头 Front
 *   前左 FL (M3) ------ 前右 FR (M4)
 *         |              |
 *   后左 BL (M1) ------ 后右 BR (M2)
 *        车尾 Rear
 *
 * 调用流程:
 *   1. main() 里: Motor_Init() -> Chassis_SetYawSource(&jy61p->var.yaw) -> Chassis_Init()
 *   2. 1ms 定时中断里: Chassis_Tick()  (内部每 20ms 自动执行一次 Chassis_Update_Control)
 *   3. 发指令: Chassis_Move_Forward(mm) / Chassis_Move_Left(mm) / Chassis_Rotate(deg) ...
 *   4. 判断是否完成: Chassis_Task_Is_Complete()
 * ===================================================================== */

/* ---------------------------------------------------------------------
 * 1. 轮位 -> 电机号 映射 (与 motor.h 的 MOTOR_1~MOTOR_4 对应)
 * ---------------------------------------------------------------------
 * ⚠️ 非调参项：由车轮实际接线位置决定，仅当重新接线/换轮位时才需要改动。
 * 含义: 左前轮接哪个电机通道(MOTOR_x)，依次类推；四个值必须互不相同。
 * 若改错会出现“左移变斜走/转向乱”等现象。
 * --------------------------------------------------------------------- */
#define CH_MOTOR_FL   MOTOR_3   /* 前左 -> 电机 3 */
#define CH_MOTOR_FR   MOTOR_4   /* 前右 -> 电机 4 */
#define CH_MOTOR_BL   MOTOR_1   /* 后左 -> 电机 1 */
#define CH_MOTOR_BR   MOTOR_2   /* 后右 -> 电机 2 */

/* ---------------------------------------------------------------------
 * 2. 每轮极性标定 (务必按实测调整, 见文件底部《上电标定流程》)
 * ---------------------------------------------------------------------
 * 这四个值只取 +1 或 -1, 用来告诉软件"电机/编码器的正方向朝哪边":
 *   CH_MOTOR_DIR_x : 给该轮 PWM 正值(Set_PWM(x,+pwm))时, 若车轮【向前滚】→ +1, 向后滚 → -1。
 *                    作用: 把"软件认为的前进方向"纠正成"物理前进方向"。
 *   CH_ENC_DIR_x   : 该轮向前滚时, 编码器增量(Encoder_GetDelta)若为正 → +1, 为负 → -1。
 *                    作用: 让"向前"时编码器计数变大, 闭环才不会南辕北辙。
 * ⚠️ 影响: 方向宏配错 → 该轮"越走越偏/自我抵消/转向转不动"等。标定方法见文件底部流程。
 * ⚠️ 四轮 MOTOR_DIR 与 ENC_DIR 必须成对反相才能保证物理一致, 不要只改其一。
 * --------------------------------------------------------------------- */
#define CH_MOTOR_DIR_FL   (-1)
#define CH_MOTOR_DIR_FR   (-1)
#define CH_MOTOR_DIR_BL   (-1)
#define CH_MOTOR_DIR_BR   (-1)

#define CH_ENC_DIR_FL     (-1)
#define CH_ENC_DIR_FR     (-1)
#define CH_ENC_DIR_BL     (-1)
#define CH_ENC_DIR_BR     (+1)

/* ---------------------------------------------------------------------
 * 方向镜像开关 (只取 +1 或 -1)
 * 作用: 整体修正"指令方向"与"实际运动方向"不一致的问题, 不用逐个轮改。
 * 默认值: 均为 +1 (已按实测标定正确)。
 *   CH_STRAFE_SIGN : 若按下"左移"指令车实际【右移】→ 改为 -1。影响所有左右平移。
 *   CH_TURN_SIGN   : 若 Chassis_Rotate(正角度) 车实际【右转】(与预期相反) → 改为 -1。
 * ⚠️ 一次只改一个并实测, 别同时盲改两个, 否则可能"方向既反又不反"难排查。
 * --------------------------------------------------------------------- */
#define CH_STRAFE_SIGN    (+1)
#define CH_TURN_SIGN      (+1)

/* ---------------------------------------------------------------------
 * 3. 底盘物理参数 (mm <-> 编码器计数 换算)
 * ---------------------------------------------------------------------
 * 作用: 软件靠这三项把"毫米距离"换算成"编码器计数", 距离才走得准。
 * 调参影响: 若走 100mm 实测不足(如 90mm)→ 需调大 CH_COUNTS_PER_MM 方向的值; 反之亦然。
 * 一般无需修改, 除非: 换了轮子直径 / 换了减速电机 / 换了编码器。
 *   CH_WHEEL_DIAMETER_MM      : 轮子直径(mm), 默认 75(按实车轮量周长更准)。
 *   CH_WHEEL_PERIMETER_MM     : 轮子周长 = 直径×π (由上面自动算, 勿手改)。
 *   CH_ENCODER_COUNTS_PER_REV : 轮子转一圈编码器计几个数 = 线数×4倍频×减速比, 默认 1560。
 *   CH_COUNTS_PER_MM          : 每毫米对应多少计数 = 一圈计数÷周长 (自动算, 勿手改)。
 * --------------------------------------------------------------------- */
#define CH_WHEEL_DIAMETER_MM        75.0f            /* 轮子直径 (mm) */
#define CH_WHEEL_PERIMETER_MM       (CH_WHEEL_DIAMETER_MM * 3.14159265f)
#define CH_ENCODER_COUNTS_PER_REV   1560.0f          /* 一圈编码器计数 (13线 x 4倍频 x 30减速比) */
#define CH_COUNTS_PER_MM            (CH_ENCODER_COUNTS_PER_REV / CH_WHEEL_PERIMETER_MM)

/* ---------------------------------------------------------------------
 * 每轮 counts/mm 标定系数 (静态轮径差异补偿)
 * 取值范围: 建议 0.90~1.10, 当前默认全为 1.00 (中性)。
 * 作用: 该系数会把"该轮目标距离"按比例缩放。例如 BL 设 1.05 → 后左轮多跑 5% 计数。
 * 影响: 某轮系数偏大→该轮走更远才到点; 四轮不齐→直线跑斜、停车瞬间甩尾。
 * ⚠️ 注意: 之前按"每轮速度差"设的 BL 0.94 / BR 1.05 是反的——它让 BR 目标最大、
 * BL 目标最小 → 四轮不同时到点, 停车瞬间后轮单独动导致甩尾(实测左移-8°、直行+2°)。
 * 现改为全 1.0(中性), 轮速差交给航向保持(速度偏置)实时修正;
 * 若要静态标定, 需实测每轮同距离下的编码器计数后再微调。
 * --------------------------------------------------------------------- */
#define CH_WHEEL_SCALE_FL            (1.00f)
#define CH_WHEEL_SCALE_FR            (1.00f)
#define CH_WHEEL_SCALE_BL            (1.00f)
#define CH_WHEEL_SCALE_BR            (1.00f)

//CH_WHEEL_SCALE (轮径/距离标定) 解决的是“走多远”（位置/距离）的问题。是在宏观上抹平四个轮子“腿长不一”的几何误差；
//CH_PWM_SCALE (电机增益标定) 解决的是“跑多快”（速度/动力）的问题。是在微观上抹平四个轮子“力气大小不一”的动力学误差

/* ---------------------------------------------------------------------
 * 每轮 PWM 补偿系数 (电机增益标定, 分前进/后退两组)
 * 取值范围: 建议 0.7~1.4, 每轮两值独立。当前为 2026-09-03 实测平衡基线。
 * 作用: 弱电机多给 PWM、强电机少给, 使四轮同 PWM 时实际转速尽量一致。
 *   FWD_xx : 该轮【前进】(正 PWM)时的补偿;  REV_xx : 该轮【后退】(负 PWM)时的补偿。
 * 影响(以 BR 为例): 系数调大→BR 得到更多 PWM → 转向/前进时 BR 更容易多出力、
 * 车头会向 BR 一侧偏; 调小则相反。前进与后退要分别调。
 * ⚠️ 实测教训: 盲目把 FWD_BR 调到 1.35 / REV_BR 1.10 会让左移对角速度失衡
 * (后退对角 647+640 ≈ 前进对角 560+590, 差 ~10%) → 横移途中持续右转 + 停车甩尾,
 * 比原版更差。真正让"后面前进歪"的是转向到位阈值过大, 已用 1.5° 阈值 + kp/kd 1.5 解决。
 * 参考测量(静止单轮, 注意带载会变): 正转 BL=1518 BR=1858 FL=1358 FR=1336;
 * 反转 BL=1761 BR=1359 FL=1392 FR=1408。补偿系数 = 该方向四轮平均增益 ÷ 该轮增益。
 * --------------------------------------------------------------------- */
#define CH_PWM_SCALE_FWD_FL          (1.061f)
#define CH_PWM_SCALE_FWD_FR          (1.061f)
#define CH_PWM_SCALE_FWD_BL          (0.83f)
#define CH_PWM_SCALE_FWD_BR          (1.12f)

#define CH_PWM_SCALE_REV_FL          (1.12f)
#define CH_PWM_SCALE_REV_FR          (1.16f)
#define CH_PWM_SCALE_REV_BL          (0.98f)
#define CH_PWM_SCALE_REV_BR          (0.90f)

/* ---------------------------------------------------------------------
 * 4. 控制参数 (可按实测调整, 单位/含义见每行)
 * --------------------------------------------------------------------- */
#define CH_CTRL_PERIOD_MS           20               /* 控制周期 (ms), 必须与 Chassis_Tick 的分频一致。
                                                      * 一般勿改: 调小→控制更勤(占 CPU), 调大→响应变钝 */

/* ---------------------------------------------------------------------
 * 启动软启动 (阶梯递增) —— 消除“起步猛冲/抬头/甩尾”
 * ---------------------------------------------------------------------
 * 含义: 每个控制周期(CH_CTRL_PERIOD_MS)内, 电机 PWM 的【幅值】最多增加
 *       CH_PWM_RAMP_STEP; 只在“幅值变大”(起步/加速)时限速,
 *       减速/反向不受影响 → 刹车与换向仍然干脆。
 * 取值范围: 0~99; 0 = 关闭软启动(恢复原来一步到位)。
 * 推荐/默认: 6 (0→满量程 99 约 17 个周期 ≈ 340ms 爬升)。
 * 影响: 调小 → 起步更柔和, 但到目标速度更慢、长距离耗时略增;
 *       调大 → 接近原来的猛冲; 设为 0 完全关闭。
 * 若起步仍冲 → 继续调小(4~5); 若觉得加速太肉 → 调大(8~12)。
 * --------------------------------------------------------------------- */
#define CH_PWM_RAMP_STEP            6               // 每个控制周期内 PWM 幅值的最大变化量

#define CH_POS_THRESHOLD_COUNT      20               /* 平移"到位判定"的允许误差 (编码器计数) ≈ 3.0mm。
                                                      * ⚠️ 2026-09-27: 45(≈6.8mm) → 20。到位后本段即
                                                      * "冻结"(目标=当前位置, 电机输出 0), 不再让位置环
                                                      * 继续去"找残差"; 所以残差留多少就直接等于"停下后
                                                      * 还会再拱多少"——45 计数(6.8mm)四轮方向不同时
                                                      * 车会被拧 ~1°, 肉眼就是"停下时轮子又动一下"。
                                                      * 配合 pid.c 位置环积分(pos_Ki)一起用才收敛得稳。
                                                      * 调小→更准但可能停得久(有 CH_MOVE_TIMEOUT_MS 兜底);
                                                      * 调大→提前判完成(没走够, 停稳后仍会挪那一段) */
#define CH_STOP_SPEED_THRESHOLD     1                /* 判"停稳"要求的速度上限 (计数/周期) ≈ 7.5mm/s。
                                                      * ⚠️ 原 5(≈38mm/s)/2(≈15mm/s): 车还在爬就被判"停稳"。
                                                      * 调小→要彻底停稳才放行(更稳但耗时);
                                                      * 调大→速度还高就放行(易残留漂移) */
#define CH_MOVE_TIMEOUT_MS          10000            /* 单段平移安全兜底(ms): 超过该时长仍未判到位就强制结束
                                                      * 本段(日志里 MOVE 行带 TO 前缀), 防止某轮被卡住时状
                                                      * 态机永远停在原地。最长一段 990mm 约 4s, 一般不会触发 */
#define CH_STOP_STABLE_COUNT        4                /* 连续 N 个控制周期都满足"位置+速度达标"才判平移到位。
                                                      * 建议 3~8。调大→防误判但每次停车多等一会 */
#define CH_MAX_TURN_ADJUST          22.0f            /* 转向修正量单次限幅 (计数/周期)。
                                                      * 建议 15~50。太小→大角度转向慢; 太大→转向起步猛 */
#define CH_ANGLE_ERR_THRESHOLD      0.7f             /* 转向死区/到位阈值 (度)。
                                                      * ⚠️ 2026-09-27 1.5 → 0.5: 本工程所有"航向校正"都是
                                                      * Chassis_Rotate_To(0), 而要修的角度正好是 1~4°。
                                                      * 阈值 1.5 时, 剩余角 <1.5° 会整个跳过 PID → adj=0 →
                                                      * 车一度都不动, 140ms 后就报"校正完成" → 每次校
                                                      * 正残留约 1.4°, 20 多处累积后车头漂到 ±5°。
                                                      * 日志铁证: STEER on=1 err=0.00 P=0.00 I=0.00 out=0.00
                                                      * integ=0.0(一次 PID 都没跑)。
                                                      * 调小→转得更准但更难"判到位"(末段会慢一点);
                                                      * 调大→容易到位但方向残留偏差大 */
#define CH_TURN_RATE_THRESHOLD      0.5f             /* 判"停稳"的角速度上限 (度/控制周期)。
                                                      * ⚠️ 原 1.0 = 50°/s: 车还在 50°/s 转就被判"转完"→
                                                      * 切走状态后电机被切断, 靠惯性又多转 1~2°(实测
                                                      * "停下时还会再扭一下")。0.5 = 25°/s。
                                                      * 建议 0.3~1.0。调小→必须几乎停稳才结束转向 */
#define CH_TURN_STABLE_COUNT        7                /* 连续 N 个周期误差足够小才判转向完成(防惯性晃过)。
                                                      * 建议 5~10。调大→转向更稳但稍慢 */

/* ---------------------------------------------------------------------
 * 转向死区内的"角速度阻尼刹车" (2026-09-27 新增) —— 消除切状态时"多转"
 * ---------------------------------------------------------------------
 * 背景: 当 |剩余角| < CH_ANGLE_ERR_THRESHOLD 时, 原代码会整个跳过转向 PID
 *       (adj=0) → 不再给任何制动 → 车带着角速度惯性继续转, 而状态机已切走,
 *       表现为"多转/没停在原地"。
 * 作用: 死区内改为输出 adj = -CH_TURN_BRAKE_KD × dyaw
 *       (dyaw = 本控制周期实测转角, 度/周期)。车还在转 → 给反向修正 → 主动刹住。
 * 取值: 0~15; 0 = 关闭(恢复原来"放任滑行")。
 * 推荐/默认: 5.0。量级参考: 转向过程 adj 的上限是 CH_MAX_TURN_ADJUST(30)。
 * 影响: 调大→停得更干脆不甩尾, 但过大可能"刹过头"反向晃一下;
 *       调小→效果变弱。
 * 调参: 切状态时还明显甩一下 → 5→8; 停车前后出现反向摆 → 8→2~3。
 * 可配合把 CH_TURN_RATE_THRESHOLD 从 3.0 改小(如 1.0) 一起用效果最好。
 * --------------------------------------------------------------------- */
#define CH_TURN_BRAKE_KD            6.0f

/* ---------------------------------------------------------------------
 * 航向保持的"位置目标微调"(trim) —— 2026-09-27 新增, 专治"平移走不直"
 * ---------------------------------------------------------------------
 * 为什么需要: 麦克纳姆轮横移时, 辊子侧向刮地被地面"拧"着转向(scrub yaw),
 *   而四轮位置环又强制每轮走完各自的计数目标 → 只靠"速度环偏置"(vel_bias)
 *   修不动: 位置环看到某轮落后就会自动加大输出, 把偏置抵消掉。
 *   日志实测: vb 已经到 ±10 计数/周期(≈±75mm/s 差速), 车头仍以 ~1~3°/s 漂。
 * 做法: 把航向 PID 的输出【累加进位置目标】(和原地转向同一个机制):
 *   FL/BL 目标 += trim, FR/BR 目标 -= trim  → 强制左右两侧轮子"走的距离不同",
 *   这才是真正能产生(并保持)偏航的手段; 到段末四轮都停在各自目标上,
 *   残差照样收敛, 不会被 trim 干扰。
 * 取值: CH_HEADING_TRIM_MAX  单位=编码器计数(单轮多走/少走多少), 250≈38mm≈±14°
 *       CH_HEADING_TRIM_STEP 每个控制周期 trim 最多变多少(速率限幅, 防过冲)
 *       每套分段参数里的 hd_trim = trim 占 PID 输出的比例(0=关闭, 只用速度偏置)
 * 影响: 调大→纠偏更狠更快; 调太大会在直线上左右摆(过冲) → 先降 hd_Kp/hd_trim,
 *       仍不够再降 hd_Kd 或 CH_HEADING_TRIM_STEP(降到 2)。
 * ⚠️ 与原地转向不冲突: 转向环改的是 s_target, 这里改的是 s_heading_trim,
 *    两者相加后才是生效目标; 到位判定/日志都已按"生效目标"计算。
 * --------------------------------------------------------------------- */
#define CH_HEADING_TRIM_MAX         250              /* 微调量绝对上限 (计数, 0=关闭) */
#define CH_HEADING_TRIM_STEP        3                /* 每周期微调量最大变化 (计数/周期) */

/* ---------------------------------------------------------------------
 * 航向保持 (陀螺仪): 运动时实时修正车头方向漂移(输出为速度环偏置)。
 * ⭐ 已改为"分段参数": 直行与平移各一套 —— 见 Chassis.c 顶部的
 *    ChassisPidCfg_t / s_cfg_straight(直行, 已调好勿动) / s_cfg_strafe(平移, 调这个)。
 *    其中的 hd_Kp / hd_Ki / hd_Kd / hd_max / hd_imax / hd_dead
 *    即原来的 CH_HEADING_KP / KI / KD / MAX / INTEGRAL_MAX / DEADZONE (初值相同)。
 * “平移走不直/漂移”优先调 s_cfg_strafe 的 hd_* , 比改 PWM 补偿更直接、更安全。
 * --------------------------------------------------------------------- */

