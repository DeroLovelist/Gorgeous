/* =====================================================================
 * Chassis 底盘运动控制模块 (麦克纳姆轮)
 * ---------------------------------------------------------------------
 * 依赖:
 *   - motor.c   : Motor_Init() / Set_PWM(n, pwm)   (PWM 与方向)
 *   - ENCODER.c : Encoder_GetDelta(n)              (编码器增量)
 *   - pid.c     : 串级 PID + 转向 PID
 *   - JY61P     : 航向角 (仅转向闭环用, 由 Chassis_SetYawSource 注入)
 *
 * 车轮布局 (车头向前, 从底面向上看):
 *
 *        车头 Front
 *   前左 FL (M3) ------ 前右 FR (M4)
 *         |              |
 *   后左 BL (M1) ------ 后右 BR (M2)
 *        车尾 Rear
 *
 * 调用流程:
 *   1. main() 里: Motor_Init() -> Chassis_SetYawSource(&jy61p->var.yaw) -> Chassis_Init()
 *   2. 1ms 定时中断里: Chassis_Tick()  (内部每 20ms 自动执行一次 Chassis_Update_Control)
 *   3. 发指令: Chassis_Move_Forward(mm) / Chassis_Move_Left(mm) / Chassis_Rotate(deg) ...
 *   4. 判断是否完成: Chassis_Task_Is_Complete()
 * ===================================================================== */

/* ---------------------------------------------------------------------
 * 1. 轮位 -> 电机号 映射 (与 motor.h 的 MOTOR_1~MOTOR_4 对应)
 * ---------------------------------------------------------------------
 * ⚠️ 非调参项：由车轮实际接线位置决定，仅当重新接线/换轮位时才需要改动。
 * 含义: 左前轮接哪个电机通道(MOTOR_x)，依次类推；四个值必须互不相同。
 * 若改错会出现“左移变斜走/转向乱”等现象。
 * --------------------------------------------------------------------- */
#define CH_MOTOR_FL   MOTOR_3   /* 前左 -> 电机 3 */
#define CH_MOTOR_FR   MOTOR_4   /* 前右 -> 电机 4 */
#define CH_MOTOR_BL   MOTOR_1   /* 后左 -> 电机 1 */
#define CH_MOTOR_BR   MOTOR_2   /* 后右 -> 电机 2 */

/* ---------------------------------------------------------------------
 * 2. 每轮极性标定 (务必按实测调整, 见文件底部《上电标定流程》)
 * ---------------------------------------------------------------------
 * 这四个值只取 +1 或 -1, 用来告诉软件"电机/编码器的正方向朝哪边":
 *   CH_MOTOR_DIR_x : 给该轮 PWM 正值(Set_PWM(x,+pwm))时, 若车轮【向前滚】→ +1, 向后滚 → -1。
 *                    作用: 把"软件认为的前进方向"纠正成"物理前进方向"。
 *   CH_ENC_DIR_x   : 该轮向前滚时, 编码器增量(Encoder_GetDelta)若为正 → +1, 为负 → -1。
 *                    作用: 让"向前"时编码器计数变大, 闭环才不会南辕北辙。
 * ⚠️ 影响: 方向宏配错 → 该轮"越走越偏/自我抵消/转向转不动"等。标定方法见文件底部流程。
 * ⚠️ 四轮 MOTOR_DIR 与 ENC_DIR 必须成对反相才能保证物理一致, 不要只改其一。
 * --------------------------------------------------------------------- */
#define CH_MOTOR_DIR_FL   (-1)
#define CH_MOTOR_DIR_FR   (-1)
#define CH_MOTOR_DIR_BL   (-1)
#define CH_MOTOR_DIR_BR   (-1)

#define CH_ENC_DIR_FL     (-1)
#define CH_ENC_DIR_FR     (-1)
#define CH_ENC_DIR_BL     (-1)
#define CH_ENC_DIR_BR     (+1)

/* ---------------------------------------------------------------------
 * 方向镜像开关 (只取 +1 或 -1)
 * 作用: 整体修正"指令方向"与"实际运动方向"不一致的问题, 不用逐个轮改。
 * 默认值: 均为 +1 (已按实测标定正确)。
 *   CH_STRAFE_SIGN : 若按下"左移"指令车实际【右移】→ 改为 -1。影响所有左右平移。
 *   CH_TURN_SIGN   : 若 Chassis_Rotate(正角度) 车实际【右转】(与预期相反) → 改为 -1。
 * ⚠️ 一次只改一个并实测, 别同时盲改两个, 否则可能"方向既反又不反"难排查。
 * --------------------------------------------------------------------- */
#define CH_STRAFE_SIGN    (+1)
#define CH_TURN_SIGN      (+1)

/* ---------------------------------------------------------------------
 * 3. 底盘物理参数 (mm <-> 编码器计数 换算)
 * ---------------------------------------------------------------------
 * 作用: 软件靠这三项把"毫米距离"换算成"编码器计数", 距离才走得准。
 * 调参影响: 若走 100mm 实测不足(如 90mm)→ 需调大 CH_COUNTS_PER_MM 方向的值; 反之亦然。
 * 一般无需修改, 除非: 换了轮子直径 / 换了减速电机 / 换了编码器。
 *   CH_WHEEL_DIAMETER_MM      : 轮子直径(mm), 默认 75(按实车轮量周长更准)。
 *   CH_WHEEL_PERIMETER_MM     : 轮子周长 = 直径×π (由上面自动算, 勿手改)。
 *   CH_ENCODER_COUNTS_PER_REV : 轮子转一圈编码器计几个数 = 线数×4倍频×减速比, 默认 1560。
 *   CH_COUNTS_PER_MM          : 每毫米对应多少计数 = 一圈计数÷周长 (自动算, 勿手改)。
 * --------------------------------------------------------------------- */
#define CH_WHEEL_DIAMETER_MM        75.0f            /* 轮子直径 (mm) */
#define CH_WHEEL_PERIMETER_MM       (CH_WHEEL_DIAMETER_MM * 3.14159265f)
#define CH_ENCODER_COUNTS_PER_REV   1560.0f          /* 一圈编码器计数 (13线 x 4倍频 x 30减速比) */
#define CH_COUNTS_PER_MM            (CH_ENCODER_COUNTS_PER_REV / CH_WHEEL_PERIMETER_MM)

/* ---------------------------------------------------------------------
 * 每轮 counts/mm 标定系数 (静态轮径差异补偿)
 * 取值范围: 建议 0.90~1.10, 当前默认全为 1.00 (中性)。
 * 作用: 该系数会把"该轮目标距离"按比例缩放。例如 BL 设 1.05 → 后左轮多跑 5% 计数。
 * 影响: 某轮系数偏大→该轮走更远才到点; 四轮不齐→直线跑斜、停车瞬间甩尾。
 * ⚠️ 注意: 之前按"每轮速度差"设的 BL 0.94 / BR 1.05 是反的——它让 BR 目标最大、
 * BL 目标最小 → 四轮不同时到点, 停车瞬间后轮单独动导致甩尾(实测左移-8°、直行+2°)。
 * 现改为全 1.0(中性), 轮速差交给航向保持(速度偏置)实时修正;
 * 若要静态标定, 需实测每轮同距离下的编码器计数后再微调。
 * --------------------------------------------------------------------- */
#define CH_WHEEL_SCALE_FL            (1.00f)
#define CH_WHEEL_SCALE_FR            (1.00f)
#define CH_WHEEL_SCALE_BL            (1.00f)
#define CH_WHEEL_SCALE_BR            (1.00f)

//CH_WHEEL_SCALE (轮径/距离标定) 解决的是“走多远”（位置/距离）的问题。是在宏观上抹平四个轮子“腿长不一”的几何误差；
//CH_PWM_SCALE (电机增益标定) 解决的是“跑多快”（速度/动力）的问题。是在微观上抹平四个轮子“力气大小不一”的动力学误差

/* ---------------------------------------------------------------------
 * 每轮 PWM 补偿系数 (电机增益标定, 分前进/后退两组)
 * 取值范围: 建议 0.7~1.4, 每轮两值独立。当前为 2026-09-03 实测平衡基线。
 * 作用: 弱电机多给 PWM、强电机少给, 使四轮同 PWM 时实际转速尽量一致。
 *   FWD_xx : 该轮【前进】(正 PWM)时的补偿;  REV_xx : 该轮【后退】(负 PWM)时的补偿。
 * 影响(以 BR 为例): 系数调大→BR 得到更多 PWM → 转向/前进时 BR 更容易多出力、
 * 车头会向 BR 一侧偏; 调小则相反。前进与后退要分别调。
 * ⚠️ 实测教训: 盲目把 FWD_BR 调到 1.35 / REV_BR 1.10 会让左移对角速度失衡
 * (后退对角 647+640 ≈ 前进对角 560+590, 差 ~10%) → 横移途中持续右转 + 停车甩尾,
 * 比原版更差。真正让"后面前进歪"的是转向到位阈值过大, 已用 1.5° 阈值 + kp/kd 1.5 解决。
 * 参考测量(静止单轮, 注意带载会变): 正转 BL=1518 BR=1858 FL=1358 FR=1336;
 * 反转 BL=1761 BR=1359 FL=1392 FR=1408。补偿系数 = 该方向四轮平均增益 ÷ 该轮增益。
 * --------------------------------------------------------------------- */
// 前进
#define CH_PWM_SCALE_FWD_FL          (1.00f)//(1.061f)
#define CH_PWM_SCALE_FWD_FR          (1.10f)//(1.061f)
#define CH_PWM_SCALE_FWD_BL          (1.00f)//(0.83f)
#define CH_PWM_SCALE_FWD_BR          (1.00f)//(1.12f)
// 后退 
#define CH_PWM_SCALE_REV_FL          (1.10f)//(1.12f)
#define CH_PWM_SCALE_REV_FR          (1.00f)//(1.00f)
#define CH_PWM_SCALE_REV_BL          (1.00f)//(0.98f)
#define CH_PWM_SCALE_REV_BR          (1.08f)//(0.90f)

/* ⚠️ 2026-10-01: REV_FR / REV_BL 试过 1.06 (想给右移时落后的 FR/BL 补 PWM),
 * 实测【无效】且略差: 右移段四轮离散度 0.29% → 2.1%, 段末同样 {FL,BR} 停 /
 * {FR,BL} 走、同样甩 3°, 前向"斜飘" +34mm/−36mm 一点没变。
 * 结论: 右移时的速度差不是"PWM 给少了"造成的(PWM 已经在速度环里被调平),
 * 所以按 PWM 系数补力这条路走不通 → 已改回 1.00, 改走 Chassis.c 的"同步降速"。 */

