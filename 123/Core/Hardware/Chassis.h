/**
 * @brief 设置"平移时保持的航向基准" (绝对角度, 单位: 度)
 * @param deg 希望车头保持的角度。本工程所有"航向校正"都是转到 0°,
 *            故任务开始时设 0° 即可(见 Mission_Init)。
 * @note  ⚠️ 2026-09-27 起: 平移【不再】自动把基准设成"当前朝向"。
 *        原来 add_move() 里每段都 `s_heading_target = *s_yaw` → 上一段航向
 *        校正剩下的 ~1.5° 误差被当成"正确朝向"继承下去, 误差只累积不回收
 *        (实测 yaw 一路漂到 ±5°), 这是"停不回原来朝向"的主因之一。
 */
void Chassis_SetHeadingRef(float deg);

/**
 * @brief 把四轮"目标位置"对齐到"当前位置" (丢弃累积的位置误差)
 * @note  只在"重新开始 / 复位 / 示教"时调用(如 Mission_Init、ArmTeach_Enter)。
 *        ⚠️ 不要放回 Chassis_Stop() 里: 每段结束时累积的残差要靠它自动补回,
 *        一被抹掉就永久留在车姿上了(车会越走越偏)。
 */
void Chassis_SyncTarget(void);

/* ---------------- 编码器静态标定 (人工推车测 counts/mm) ---------------- */

/**
 * @brief  开始编码器静态标定: 挂起底盘(电机不输出)、清零累计计数
 * @note   用途: 测"每轮走同样距离时各报多少编码器计数" → 标定 CH_WHEEL_SCALE_*
 *         (该轮实测 counts/mm ÷ 标称 CH_COUNTS_PER_MM)。
 *
 *         ⚠️ 为什么必须【人工推车】测, 不能看正常跑车的日志:
 *            正常跑车时位置闭环会把每轮都控到各自的计数目标, 所以四轮打印的
 *            计数几乎一样 (MOVE 日志的 d: 也就差不多), 根本看不出真实的
 *            counts/mm 差异。只有挂起闭环、纯滚动推动才测得到。
 *
 *         ⚠️ 什么时候才该用静态标定(重要):
 *            同一个方向推两次、正反各推一次, 结果应该很接近 (差 <0.5%)。
 *            - 四个系数稳定且某轮明显偏离 1.000 → 是 counts/mm 差异, 用静态
 *              标定能修。
 *            - 如果"有时 M1 多、有时 M2 多"或正反推不一致 → 不是 counts/mm
 *              问题(是打滑/静摩擦/负载转移/轮子被抬起), 静态标定修不了:
 *              硬改只会把偏差从一段挪到另一段。
 *
 *         用法: Chassis_CalibStart() → 推车(过程中周期调 Chassis_CalibPoll())
 *               → Chassis_CalibReport(实测距离mm) → Chassis_CalibStop()
 */
void Chassis_CalibStart(void);

/**
 * @brief  标定过程中周期调用(主循环里每 20~100ms 一次), 累计四轮编码器计数
 * @note   只能在 Chassis_CalibStart() 之后、底盘挂起期间调
 */
void Chassis_CalibPoll(void);

/**
 * @brief  读取某轮的标定累计计数 (前进为正, 即已乘过 CH_ENC_DIR)
 * @param  idx 0=FL 1=FR 2=BL 3=BR
 */
int32_t Chassis_CalibAccum(int idx);

/**
 * @brief  按"人工推车距离"打印四轮计数与建议的 CH_WHEEL_SCALE_*
 * @param  distance_mm 用卷尺量准的实际推动距离(mm), 建议 1000
 * @note   会打印两行 I/CALIB; 第二行是乘 1000 的系数, 例如 FR=1027 表示把
 *         CH_WHEEL_SCALE_FR 改成 1.027f (1000 = 不用改)。
 */
void Chassis_CalibReport(float distance_mm);

/**
 * @brief  结束标定并恢复正常闭环 (内部调 Chassis_Resume)
 */
void Chassis_CalibStop(void);

/**
 * @brief 1ms 周期调用 (放在 1ms 定时中断里), 内部每 20ms 执行一次控制
 */
void Chassis_Tick(void);
/**
 * @brief  挂起底盘控制 (停止读写电机/编码器)
 * @note   手动测试电机(如 MotorTest)前调用, 避免底盘闭环覆盖手动 PWM
 */
void Chassis_Suspend(void);

/**
 * @brief  恢复底盘控制 (重新同步编码器并清零位置目标)
 */
void Chassis_Resume(void);
/**
 * @brief 底盘控制更新 (位置闭环 + 转向闭环 + 输出 PWM)
 * @note  内部固定按 CH_CTRL_PERIOD_MS 周期调用, 也可直接周期调用
 */
void Chassis_Update_Control(void);

/* ---------------- 平移指令 (距离, 单位: mm) ---------------- */
void Chassis_Move_Forward(int32_t distance_mm);
void Chassis_Move_Backward(int32_t distance_mm);
void Chassis_Move_Left(int32_t distance_mm);
void Chassis_Move_Right(int32_t distance_mm);

/**
 * @brief 斜向移动: fwd_mm 前进(>0)/后退(<0), strafe_mm 左移(>0)/右移(<0)
 */
void Chassis_Move_Diagonal(int32_t fwd_mm, int32_t strafe_mm);

/* ---------------- 转向指令 (角度, 单位: 度) ---------------- */

/**
 * @brief 相对旋转 delta_deg (正=逆时针/向左转, 负=顺时针/向右转)
 * @note  需要 Chassis_SetYawSource 已注入航向角
 */
void Chassis_Rotate(float delta_deg);

/**
 * @brief 旋转到指定绝对航向角 (正=逆时针)
 * @note  需要 Chassis_SetYawSource 已注入航向角; 内部计算相对角后调用 Chassis_Rotate
 */
void Chassis_Rotate_To(float target_deg);

/* ---------------- 停止 / 状态 ---------------- */

/**
 * @brief 立即停止: 清除目标, 保持当前位置 (电机刹停)
 */
void Chassis_Stop(void);

/**
 * @brief 底盘当前是否空闲 (无平移、无转向进行中)
 */
bool Chassis_Task_Is_Complete(void);

/**
 * @brief 演示程序 (非阻塞状态机, 放在主循环里调用即可):
 *        前进300 -> 左移300 -> 右移300 -> 旋转180 -> 后退300, 循环
 */
void Chassis_Demo(void);

/**
 * @brief  重置演示状态机 (从“前进”重新开始) 并停止底盘
 */
void Chassis_Demo_Reset(void);

/**
 * @brief  打印底盘调试信息 (演示步进/目标/当前位置/转向剩余), 供诊断
 * @note   需在主循环中周期调用, 勿在中断中调用
 */
void Chassis_DebugLog(void);

/**
 * @brief  打印航向保持调试信息 (误差/积分/修正/速度偏置), 供诊断
 * @note   需在主循环中周期调用, 勿在中断中调用
 */
void Chassis_HeadingDebugLog(void);

/* ---------------- 转向环 PID 调试量 (供 OLED / 蓝牙打印) ---------------- */

/**
 * @brief  读取转向环 PID 的 I 项输出 (= ki × 积分累加值)
 * @note   ⚠️ 转向环当前 ki=0, 所以该值恒为 0;
 *         想看积分累积请用 Chassis_GetSteerIntegrator()
 */
float Chassis_GetSteerITerm(void);

/**
 * @brief  读取转向环 PID 的积分累加值 integrator (调试用)
 */
float Chassis_GetSteerIntegrator(void);

/**
 * @brief  读取本次转向中 |I 项| 的峰值 (峰值保持, 调试用)
 * @note   转向环只在 Chassis_Rotate() 期间运行, 非转向时恒为 0
 */
float Chassis_GetSteerIPeak(void);

/**
 * @brief  打印转向环 PID 调试信息 (误差/P/I/D/总输出/积分值), 供诊断
 * @note   需在主循环中周期调用, 勿在中断中调用;
 *         on=0 表示当前不在转向, 各值为上一次转向的残留
 */
void Chassis_SteerDebugLog(void);

