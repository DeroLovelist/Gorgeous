/* =====================================================================
 * Chassis 底盘运动控制模块 (麦克纳姆轮)
 * ---------------------------------------------------------------------
 * 依赖:
 *   - motor.c   : Motor_Init() / Set_PWM(n, pwm)   (PWM 与方向)
 *   - ENCODER.c : Encoder_GetDelta(n)              (编码器增量)
 *   - pid.c     : 串级 PID + 转向 PID
 *   - JY61P     : 航向角 (仅转向闭环用, 由 Chassis_SetYawSource 注入)
 *
 * 车轮布局 (车头向前, 从底面向上看):
 *
 *        车头 Front
 *   前左 FL (M3) ------ 前右 FR (M4)
 *         |              |
 *   后左 BL (M1) ------ 后右 BR (M2)
 *        车尾 Rear
 *
 * 调用流程:
 *   1. main() 里: Motor_Init() -> Chassis_SetYawSource(&jy61p->var.yaw) -> Chassis_Init()
 *   2. 1ms 定时中断里: Chassis_Tick()  (内部每 20ms 自动执行一次 Chassis_Update_Control)
 *   3. 发指令: Chassis_Move_Forward(mm) / Chassis_Move_Left(mm) / Chassis_Rotate(deg) ...
 *   4. 判断是否完成: Chassis_Task_Is_Complete()
 * ===================================================================== */

/* ---------------------------------------------------------------------
 * 1. 轮位 -> 电机号 映射 (与 motor.h 的 MOTOR_1~MOTOR_4 对应)
 * ---------------------------------------------------------------------
 * ⚠️ 非调参项：由车轮实际接线位置决定，仅当重新接线/换轮位时才需要改动。
 * 含义: 左前轮接哪个电机通道(MOTOR_x)，依次类推；四个值必须互不相同。
 * 若改错会出现“左移变斜走/转向乱”等现象。
 * --------------------------------------------------------------------- */
#define CH_MOTOR_FL   MOTOR_3   /* 前左 -> 电机 3 */
#define CH_MOTOR_FR   MOTOR_4   /* 前右 -> 电机 4 */
#define CH_MOTOR_BL   MOTOR_1   /* 后左 -> 电机 1 */
#define CH_MOTOR_BR   MOTOR_2   /* 后右 -> 电机 2 */

/* ---------------------------------------------------------------------
 * 2. 每轮极性标定 (务必按实测调整, 见文件底部《上电标定流程》)
 * ---------------------------------------------------------------------
 * 这四个值只取 +1 或 -1, 用来告诉软件"电机/编码器的正方向朝哪边":
 *   CH_MOTOR_DIR_x : 给该轮 PWM 正值(Set_PWM(x,+pwm))时, 若车轮【向前滚】→ +1, 向后滚 → -1。
 *                    作用: 把"软件认为的前进方向"纠正成"物理前进方向"。
 *   CH_ENC_DIR_x   : 该轮向前滚时, 编码器增量(Encoder_GetDelta)若为正 → +1, 为负 → -1。
 *                    作用: 让"向前"时编码器计数变大, 闭环才不会南辕北辙。
 * ⚠️ 影响: 方向宏配错 → 该轮"越走越偏/自我抵消/转向转不动"等。标定方法见文件底部流程。
 * ⚠️ 四轮 MOTOR_DIR 与 ENC_DIR 必须成对反相才能保证物理一致, 不要只改其一。
 * --------------------------------------------------------------------- */
#define CH_MOTOR_DIR_FL   (-1)
#define CH_MOTOR_DIR_FR   (-1)
#define CH_MOTOR_DIR_BL   (-1)
#define CH_MOTOR_DIR_BR   (-1)

#define CH_ENC_DIR_FL     (-1)
#define CH_ENC_DIR_FR     (-1)
#define CH_ENC_DIR_BL     (-1)
#define CH_ENC_DIR_BR     (+1)

/* ---------------------------------------------------------------------
 * 方向镜像开关 (只取 +1 或 -1)
 * 作用: 整体修正"指令方向"与"实际运动方向"不一致的问题, 不用逐个轮改。
 * 默认值: 均为 +1 (已按实测标定正确)。
 *   CH_STRAFE_SIGN : 若按下"左移"指令车实际【右移】→ 改为 -1。影响所有左右平移。
 *   CH_TURN_SIGN   : 若 Chassis_Rotate(正角度) 车实际【右转】(与预期相反) → 改为 -1。
 * ⚠️ 一次只改一个并实测, 别同时盲改两个, 否则可能"方向既反又不反"难排查。
 * --------------------------------------------------------------------- */
#define CH_STRAFE_SIGN    (+1)
#define CH_TURN_SIGN      (+1)

/* ---------------------------------------------------------------------
 * 3. 底盘物理参数 (mm <-> 编码器计数 换算)
 * ---------------------------------------------------------------------
 * 作用: 软件靠这三项把"毫米距离"换算成"编码器计数", 距离才走得准。
 * 调参影响: 若走 100mm 实测不足(如 90mm)→ 需调大 CH_COUNTS_PER_MM 方向的值; 反之亦然。
 * 一般无需修改, 除非: 换了轮子直径 / 换了减速电机 / 换了编码器。
 *   CH_WHEEL_DIAMETER_MM      : 轮子直径(mm), 默认 75(按实车轮量周长更准)。
 *   CH_WHEEL_PERIMETER_MM     : 轮子周长 = 直径×π (由上面自动算, 勿手改)。
 *   CH_ENCODER_COUNTS_PER_REV : 轮子转一圈编码器计几个数 = 线数×4倍频×减速比, 默认 1560。
 *   CH_COUNTS_PER_MM          : 每毫米对应多少计数 = 一圈计数÷周长 (自动算, 勿手改)。
 * --------------------------------------------------------------------- */
#define CH_WHEEL_DIAMETER_MM        75.0f            /* 轮子直径 (mm) */
#define CH_WHEEL_PERIMETER_MM       (CH_WHEEL_DIAMETER_MM * 3.14159265f)
#define CH_ENCODER_COUNTS_PER_REV   1560.0f          /* 一圈编码器计数 (13线 x 4倍频 x 30减速比) */
#define CH_COUNTS_PER_MM            (CH_ENCODER_COUNTS_PER_REV / CH_WHEEL_PERIMETER_MM)

/* ---------------------------------------------------------------------
 * 每轮 counts/mm 标定系数 (静态轮径差异补偿)
 * 取值范围: 建议 0.90~1.10, 当前默认全为 1.00 (中性)。
 * 作用: 该系数会把"该轮目标距离"按比例缩放。例如 BL 设 1.05 → 后左轮多跑 5% 计数。
 * 影响: 某轮系数偏大→该轮走更远才到点; 四轮不齐→直线跑斜、停车瞬间甩尾。
 * ⚠️ 注意: 之前按"每轮速度差"设的 BL 0.94 / BR 1.05 是反的——它让 BR 目标最大、
 * BL 目标最小 → 四轮不同时到点, 停车瞬间后轮单独动导致甩尾(实测左移-8°、直行+2°)。
 * 现改为全 1.0(中性), 轮速差交给航向保持(速度偏置)实时修正;
 * 若要静态标定, 需实测每轮同距离下的编码器计数后再微调。
 * --------------------------------------------------------------------- */
#define CH_WHEEL_SCALE_FL            (1.00f)
#define CH_WHEEL_SCALE_FR            (1.00f)
#define CH_WHEEL_SCALE_BL            (1.00f)
#define CH_WHEEL_SCALE_BR            (1.00f)

//CH_WHEEL_SCALE (轮径/距离标定) 解决的是“走多远”（位置/距离）的问题。是在宏观上抹平四个轮子“腿长不一”的几何误差；
//CH_PWM_SCALE (电机增益标定) 解决的是“跑多快”（速度/动力）的问题。是在微观上抹平四个轮子“力气大小不一”的动力学误差

/* ---------------------------------------------------------------------
 * 每轮 PWM 补偿系数 (电机增益标定, 分前进/后退两组)
 * 取值范围: 建议 0.7~1.4, 每轮两值独立。当前为 2026-09-03 实测平衡基线。
 * 作用: 弱电机多给 PWM、强电机少给, 使四轮同 PWM 时实际转速尽量一致。
 *   FWD_xx : 该轮【前进】(正 PWM)时的补偿;  REV_xx : 该轮【后退】(负 PWM)时的补偿。
 * 影响(以 BR 为例): 系数调大→BR 得到更多 PWM → 转向/前进时 BR 更容易多出力、
 * 车头会向 BR 一侧偏; 调小则相反。前进与后退要分别调。
 * ⚠️ 实测教训: 盲目把 FWD_BR 调到 1.35 / REV_BR 1.10 会让左移对角速度失衡
 * (后退对角 647+640 ≈ 前进对角 560+590, 差 ~10%) → 横移途中持续右转 + 停车甩尾,
 * 比原版更差。真正让"后面前进歪"的是转向到位阈值过大, 已用 1.5° 阈值 + kp/kd 1.5 解决。
 * 参考测量(静止单轮, 注意带载会变): 正转 BL=1518 BR=1858 FL=1358 FR=1336;
 * 反转 BL=1761 BR=1359 FL=1392 FR=1408。补偿系数 = 该方向四轮平均增益 ÷ 该轮增益。
 * --------------------------------------------------------------------- */
// 前进
#define CH_PWM_SCALE_FWD_FL          (1.00f)//(1.061f)
#define CH_PWM_SCALE_FWD_FR          (1.10f)//(1.061f)
#define CH_PWM_SCALE_FWD_BL          (1.00f)//(0.83f)
#define CH_PWM_SCALE_FWD_BR          (1.00f)//(1.12f)
// 后退 
#define CH_PWM_SCALE_REV_FL          (1.10f)//(1.12f)
#define CH_PWM_SCALE_REV_FR          (1.00f)//(1.00f)
#define CH_PWM_SCALE_REV_BL          (1.00f)//(0.98f)
#define CH_PWM_SCALE_REV_BR          (1.08f)//(0.90f)

/* ⚠️ 2026-10-01: REV_FR / REV_BL 试过 1.06 (想给右移时落后的 FR/BL 补 PWM),
 * 实测【无效】且略差: 右移段四轮离散度 0.29% → 2.1%, 段末同样 {FL,BR} 停 /
 * {FR,BL} 走、同样甩 3°, 前向"斜飘" +34mm/−36mm 一点没变。
 * 结论: 右移时的速度差不是"PWM 给少了"造成的(PWM 已经在速度环里被调平),
 * 所以按 PWM 系数补力这条路走不通 → 已改回 1.00, 改走 Chassis.c 的"同步降速"。 */

/* ---------------------------------------------------------------------
 * 4. 控制参数 (可按实测调整, 单位/含义见每行)
 * --------------------------------------------------------------------- */
#define CH_CTRL_PERIOD_MS           20               /* 控制周期 (ms), 必须与 Chassis_Tick 的分频一致。
                                                      * 一般勿改: 调小→控制更勤(占 CPU), 调大→响应变钝 */

/* ---------------------------------------------------------------------
 * 启动软启动 (阶梯递增) —— 消除“起步猛冲/抬头/甩尾”
 * ---------------------------------------------------------------------
 * 含义: 每个控制周期(CH_CTRL_PERIOD_MS)内, 电机 PWM 的【幅值】最多增加
 *       CH_PWM_RAMP_STEP; 只在“幅值变大”(起步/加速)时限速,
 *       减速/反向不受影响 → 刹车与换向仍然干脆。
 * 取值范围: 0~99; 0 = 关闭软启动(恢复原来一步到位)。
 * 推荐/默认: 6 (0→满量程 99 约 17 个周期 ≈ 340ms 爬升)。
 * 影响: 调小 → 起步更柔和, 但到目标速度更慢、长距离耗时略增;
 *       调大 → 接近原来的猛冲; 设为 0 完全关闭。
 * 若起步仍冲 → 继续调小(4~5); 若觉得加速太肉 → 调大(8~12)。
 * --------------------------------------------------------------------- */
#define CH_PWM_RAMP_STEP            6               // 每个控制周期内 PWM 幅值的最大变化量

#define CH_POS_THRESHOLD_COUNT      40               /* 平移"到位判定"的允许误差 (编码器计数) ≈ 3.8mm。
                                                      * ⚠️ 2026-09-27: 45(≈6.8mm) → 20。到位后本段即
                                                      * "冻结"(目标=当前位置, 电机输出 0), 不再让位置环
                                                      * 继续去"找残差"; 所以残差留多少就直接等于"停下后
                                                      * 还会再拱多少"——45 计数(6.8mm)四轮方向不同时
                                                      * 车会被拧 ~1°, 肉眼就是"停下时轮子又动一下"。
                                                      * 配合 pid.c 位置环积分(pos_Ki)一起用才收敛得稳。
                                                      * 调小→更准但可能停得久(有 CH_MOVE_TIMEOUT_MS 兜底);
                                                      * 调大→提前判完成(没走够, 停稳后仍会挪那一段) */
#define CH_STOP_SPEED_THRESHOLD     2                /* 判"停稳"要求的速度上限 (计数/周期) ≈ 15mm/s。
                                                      * ⚠️ 不要设成 1: 轮子静止时编码器仍有 ±1~2 计数的
                                                      * 抖动(日志里 M1=61557→61558→61558, M2=3986→3987),
                                                      * 阈值 1 = 要求"速度恰好为 0"连 4 个周期, 实测永远
                                                    * 满足不了 → 每段都判不到位、等到超时(日志里 MOVE 行
                                                      * 带 TO)→ 走过多少完全由"超时×速度"决定!!!
                                                      * 已配套: 判据改用 Chassis.c 里低通后的速度 s_speed_filt
                                                      * (时问常数 4 个周期) 滤掉抖动, 所以 2 是安全的。
                                                      * 调小→要彻底停稳才放行(更稳但耗时);
                                                      * 调大→速度还高就放行(易残留漂移) */

/* ---- 单段平移超时(自适应) -------------------------------------------------
 * ⚠️ 为什么不能写一个固定值(血泪教训): 超时是"本段结束的最后手段",
 *    一旦它比本段应耗时还短, 本段就会被它切断 → 车实际走的距离 = 速度×超时,
 *    与状态机里设的距离宏【完全无关】。现象就是"不管 ROUTE_x_MM 改成多少,
 *    车都只走同一个距离"(实测: 超时设 3000ms 时, 900mm 段只走了 ~380mm,
 *    990mm 段只走了 ~660mm, 日志都带 TO)。
 * 做法: 按本段距离自适应算超时 = 2000ms + 距离/CH_MOVE_MIN_SPEED_MMPS,
 *    上下限夹在 [MIN, MAX] 内。200mm/s 的段按 100mm/s 折算 → 余量 2 倍。
 * 最长一段 990mm → 2000+9900 = 11.9s; 100mm 段 → 3s(下限)。
 * 实测 1~2 次后如需微调, 只改 MIN_SPEED_MMPS(调大→超时更短、卡住时更早脱身,
 * 但太大会误切慢速段; 建议 80~150)。
 * --------------------------------------------------------------------- */
#define CH_MOVE_MIN_SPEED_MMPS      100              /* 折算超时用的最低平均速度 (mm/s) */
#define CH_MOVE_TIMEOUT_MIN_MS      3000             /* 超时下限 (ms): 短距离也不低于此值 */
#define CH_MOVE_TIMEOUT_MAX_MS      15000            /* 超时上限 (ms): 防止误设成大值把卡住一直拖 */
#define CH_STOP_STABLE_COUNT        4                /* 连续 N 个控制周期都满足"位置+速度达标"才判平移到位。
                                                      * 建议 3~8。调大→防误判但每次停车多等一会 */
#define CH_STOP_HOLD_MAX_MS         600              /* ⭐ 兜底: 四轮位置都已达标(在 CH_POS_THRESHOLD_COUNT 内),
                                                      * 但"速度达标"迟迟不满足时, 最多再等这么久就强制
                                                      * 结束本段(日志打 PV)。
                                                      * 为什么需要: 本工程被这个坑卡过两次 ——
                                                      * ① CH_STOP_SPEED_THRESHOLD 设 1(要求速度恰好 0);
                                                      * ② 低通速度的整数除法卡在 2~3 下不去;
                                                      * 症状都是"车早就到位了, 却每段干等 3~12s 才动
                                                      * 下一步"(MOVE 行带 TO 而 e: 已经很小)。
                                                      * 有了它, 任何阈值写过头都不会造成"停很久"。
                                                      * 建议 300~1000, 0 = 关闭 */
#define CH_MAX_TURN_ADJUST          22.0f            /* 转向修正量单次限幅 (计数/周期)。
                                                      * 建议 15~50。太小→大角度转向慢; 太大→转向起步猛 */
#define CH_ANGLE_ERR_THRESHOLD      0.35f             /* 转向死区/到位阈值 (度)。
                                                      * ⚠️ 2026-09-27 1.5 → 0.5: 本工程所有"航向校正"都是
                                                      * Chassis_Rotate_To(0), 而要修的角度正好是 1~4°。
                                                      * 阈值 1.5 时, 剩余角 <1.5° 会整个跳过 PID → adj=0 →
                                                      * 车一度都不动, 140ms 后就报"校正完成" → 每次校
                                                      * 正残留约 1.4°, 20 多处累积后车头漂到 ±5°。
                                                      * 日志铁证: STEER on=1 err=0.00 P=0.00 I=0.00 out=0.00
                                                      * integ=0.0(一次 PID 都没跑)。
                                                      * 调小→转得更准但更难"判到位"(末段会慢一点);
                                                      * 调大→容易到位但方向残留偏差大 */
#define CH_TURN_RATE_THRESHOLD      0.5f             /* 判"停稳"的角速度上限 (度/控制周期)。
                                                      * ⚠️ 原 1.0 = 50°/s: 车还在 50°/s 转就被判"转完"→
                                                      * 切走状态后电机被切断, 靠惯性又多转 1~2°(实测
                                                      * "停下时还会再扭一下")。0.5 = 25°/s。
                                                      * 建议 0.3~1.0。调小→必须几乎停稳才结束转向 */
#define CH_TURN_STABLE_COUNT        7                /* 连续 N 个周期误差足够小才判转向完成(防惯性晃过)。
                                                      * 建议 5~10。调大→转向更稳但稍慢 */

/* ---------------------------------------------------------------------
 * 转向死区内的"角速度阻尼刹车" (2026-09-27 新增) —— 消除切状态时"多转"
 * ---------------------------------------------------------------------
 * 背景: 当 |剩余角| < CH_ANGLE_ERR_THRESHOLD 时, 原代码会整个跳过转向 PID
 *       (adj=0) → 不再给任何制动 → 车带着角速度惯性继续转, 而状态机已切走,
 *       表现为"多转/没停在原地"。
 * 作用: 死区内改为输出 adj = -CH_TURN_BRAKE_KD × dyaw
 *       (dyaw = 本控制周期实测转角, 度/周期)。车还在转 → 给反向修正 → 主动刹住。
 * 取值: 0~15; 0 = 关闭(恢复原来"放任滑行")。
 * 推荐/默认: 5.0。量级参考: 转向过程 adj 的上限是 CH_MAX_TURN_ADJUST(30)。
 * 影响: 调大→停得更干脆不甩尾, 但过大可能"刹过头"反向晃一下;
 *       调小→效果变弱。
 * 调参: 切状态时还明显甩一下 → 5→8; 停车前后出现反向摆 → 8→2~3。
 * 可配合把 CH_TURN_RATE_THRESHOLD 从 3.0 改小(如 1.0) 一起用效果最好。
 * --------------------------------------------------------------------- */
#define CH_TURN_BRAKE_KD            6.0f

/* ---------------------------------------------------------------------
 * 航向保持的"位置目标微调"(trim) —— 2026-09-27 新增, 专治"平移走不直"
 * ---------------------------------------------------------------------
 * 为什么需要: 麦克纳姆轮横移时, 辊子侧向刮地被地面"拧"着转向(scrub yaw),
 *   而四轮位置环又强制每轮走完各自的计数目标 → 只靠"速度环偏置"(vel_bias)
 *   修不动: 位置环看到某轮落后就会自动加大输出, 把偏置抵消掉。
 *   日志实测: vb 已经到 ±10 计数/周期(≈±75mm/s 差速), 车头仍以 ~1~3°/s 漂。
 * 做法: 把航向 PID 的输出【累加进位置目标】(和原地转向同一个机制):
 *   FL/BL 目标 += trim, FR/BR 目标 -= trim  → 强制左右两侧轮子"走的距离不同",
 *   这才是真正能产生(并保持)偏航的手段; 到段末四轮都停在各自目标上,
 *   残差照样收敛, 不会被 trim 干扰。
 * 取值: CH_HEADING_TRIM_MAX  单位=编码器计数(单轮多走/少走多少), 250≈38mm≈±14°
 *       CH_HEADING_TRIM_STEP 每个控制周期 trim 最多变多少(速率限幅, 防过冲)
 *       每套分段参数里的 hd_trim = trim 占 PID 输出的比例(0=关闭, 只用速度偏置)
 * 影响: 调大→纠偏更狠更快; 调太大会在直线上左右摆(过冲) → 先降 hd_Kp/hd_trim,
 *       仍不够再降 hd_Kd 或 CH_HEADING_TRIM_STEP(降到 2)。
 * ⚠️ 与原地转向不冲突: 转向环改的是 s_target, 这里改的是 s_heading_trim,
 *    两者相加后才是生效目标; 到位判定/日志都已按"生效目标"计算。
 * --------------------------------------------------------------------- */
#define CH_HEADING_TRIM_MAX         80//250              /* 微调量绝对上限 (计数, 0=关闭) */
#define CH_HEADING_TRIM_STEP       1// 3               /* 每周期微调量最大变化 (计数/周期) */
/* ---------------------------------------------------------------------
 * ⭐ 2026-09-30 新增: 段末"卡住"检测 (航向环的抗饱和)
 * ---------------------------------------------------------------------
 * 背景(实测): 段末车已经停住、但位置还没判到位时, 车头即使歪着也**转不动**
 *   (靠轮子差速推不动一辆静止的车) → 航向积分只能一直涨:
 *   实测 4.5 秒内 corr 从 3.6 涨到 22.8 (= hd_max 限幅), 而速度偏置一涨就出两件事:
 *     ① pid.c 里 pos_lim = max_vel - |bias| → 位置环权限被压到只剩 8 计数/周期;
 *     ② "偏置不许把平移方向反掉"那条会把 FR/BR 的 vel_target 直接夹成 0;
 *   → 四轮互相锁死、残差永远收不掉 → 整段干等到超时(白等 4.5s, 而且残差被
 *     chassis_freeze 丢掉 → 实际走的距离比命令值短, 误差还会累积)。
 * 做法: 连续 CH_STALL_DETECT_CYCLES 个周期都满足
 *         "四轮速度 < CH_STOP_SPEED_THRESHOLD 且 位置还没到位"
 *       → 判"卡住": 清掉航向积分 + 本轮 corr/速度偏置给 0,
 *         把全部速度权限还给位置环去收残差。轮子一动立刻恢复纠偏。
 * 取值: 10 (≈200ms)。调大→更不容易误判但脱困慢; 调小→可能把"正常慢慢爬"误判,
 *       误判的后果只是这一拍不纠偏, 无害。
 * ⚠️ 2026-10-01: 又新增两个配套常量:
 *   CH_STALL_SPEED_COUNT  : 判"不动"的速度阈值 (计数/周期)。
 *     取 4(≈60mm/s)而不是 CH_STOP_SPEED_THRESHOLD(2): 段末常有某一轮以 1~3 计数/周期
 *     在"爬"(实测 M1 57492→57502), 用 2 判不出"停住" → 卡住检测失效、偏置照样涨。
 *     正常行驶时四轮都在 20~30 计数/周期, 不会误判。
 *   CH_STALL_FINISH_CYCLES: 卡住持续这么多周期就直接结束本段(日志打 "ST"),
 *     不再干等到超时(实测每段白等 3.5~4.5s)。典型场景: 横移段末某一轮
 *     (实测 FR)落后 ~180 计数, 其余三轮都到位停住了, 它单独推不动整车。
 * ⚠️ 正常行驶不会触发(速度阈值与到位判据用的都是同一套常量);
 *    清了偏置还不动 → 那才是真被机械卡住, 这时 ST 兑底帮你早点脱身。
 * --------------------------------------------------------------------- */
#define CH_STALL_DETECT_CYCLES      10
#define CH_STALL_SPEED_COUNT        6    /* ⚠️ 2026-10-01: 4 → 6 (见下面说明) */
#define CH_STALL_FINISH_CYCLES      15
/* ⚠️ 2026-10-01: CH_STALL_SPEED_COUNT 4 → 6。原因(实测 1510mm 右移段末):
 *   只剩 FL 一轮在"爬"(2~3.3 计数/周期), 但它偶尔会跳到 4 以上 → s_stall_cycles
 *   被反复清零 → 卡住检测(10 周期)和 ST 兑底(再 15 周期)全都触发不了 →
 *   白等 ~3 秒, 期间 FL 单独跑了 389 计数, 把车头拧了 5.1°(yaw −1.6°→−6.7°),
 *   后面还得靠 Turn_Angle_Compat 再扭回来。
 *   改 6 后仍然远低于正常行驶的 20~30 计数/周期, 不会误判。 */

/* ---------------------------------------------------------------------
 * ⭐ 2026-10-01 新增: 段末"停偏置"(航向环强制让权)
 * ---------------------------------------------------------------------
 * 背景(实测, 2026-10-01 日志): 横移段末航向环的 corr 会顶到 hd_max 饱和
 *   (日志里精确出现 corr=10.0 / -10.0), 而此时四轮速度已经降到 10 计数/周期 左右,
 *   一个饱和的 vel_bias 会在 pid.c 里做三件坏事:
 *     ① pos_lim = max_vel - |bias| → 位置环权限被白扣掉 |bias|;
 *     ② "偏置不许把平移方向反掉"那条, 会把残差已经很小(位置环输出很小)的轮子
 *        vel_target 直接夹成 0 → 那一侧等于被刹车;
 *     ③ 结果是"一条对角还在推、另一条已经停" = 单对角驱动 = 纯转动。
 *   日志铁证(864mm 左移段末一拍, 已折算成前进为正):
 *     FL=-46  BR=+4  (已停)   FR=+227  BL=+110  (还在走)
 *     反算 wk=(FR+BL-FL-BR)/4=+42 计数 ≈ +1.6°, 与实测 yaw 1.6°→4.3° 完全吻合。
 *   同时它也解释了为什么"加大 corr 反而治不了": 段末 corr 越大, 位置环权限越小,
 *   四轮越收不掉残差, 尾巴反而更明显。
 *
 * 做法: 四轮【最大剩余残差】< 本宏时, 本周期强制 corr=0 且清掉航向积分,
 *   即最后这十几毫米完全交给位置环: 四轮同时收残差、同时减速、同时停,
 *   段末不再被拧一下。剩下的那点角度由状态机的 Turn_Angle_Compat(0.1f) 收尾。
 *   期间 I/HDG 日志会打 corr=0.0 vb=0,0,0,0 —— 看到这个就说明本功能生效了
 *   (如果段末还是 corr=10.0 vb=10,-10,10,-10, 说明本宏设得太小、没触发到)。
 *
 * 取值: 单位 = 编码器计数(1mm ≈ 6.62 计数), 建议 100~250。
 *   150 ≈ 23mm ≈ 6 个控制周期。
 *   调大 → 更早让权(尾巴更小, 但最后一段路完全没有航向修正);
 *   调小 → 让权更晚(保留更多纠偏, 尾巴改善有限);
 *   0    → 关闭本功能(恢复原行为)。
 * ⚠️ 与 CH_STALL_* 的区别: CH_STALL_* 是"车已经不动了"的脱困兜底;
 *    本宏是"车还在动、但快到点了"的主动让权, 触发得更早(理论上更频繁)。
 * --------------------------------------------------------------------- */
#define CH_HDG_CUT_ERR_COUNT        150

/* ---------------------------------------------------------------------
 * ⭐ 2026-10-01 新增: 四轮"同步降速" (治段末"单对角推车"甩尾 + 位移斜飘)
 * ---------------------------------------------------------------------
 * 背景(实测 2026-10-01 右移 626mm 段): 四轮目标完全一样, 但实际能跑出来的速度
 *   差 15~20% (BR≈550 / FL≈470 / BL≈480 / FR≈420 计数每 500ms), 因为横移时四轮
 *   都被负载压在"速度环给不出目标速度"的区域。于是:
 *     ① 快的那条对角一路领先(t7 时 BR 已完成 96.6%, FR/BL 才 80~82%);
 *     ② 段末领先的那条先剩余为 0 → 位置环输出掉到 0 → 它停住;
 *     ③ 只剩另一条对角推车 = 绕车心纯转动 → 段末甩尾 3°(实测 −0.5°→−3.1°);
 *     ④ 而"谁领先"在整段里会翻一次符号(前 3.5s +228 计数、后 1.5s −238 计数)
 *        → 车身沿对角线"蹭出去 34mm 再蹭回来 36mm" = 你看到的"斜飘一点距离"。
 * 做法: 每周期算四轮剩余距离的平均值 r_avg, 对【领先】的轮子(r_i < r_avg)
 *   追加一个与它自己运动方向【相反】的速度环偏置:
 *       C_i = clamp(CH_SYNC_GAIN × (r_avg - r_i), 0, CH_SYNC_MAX)
 *   经 pid.c 的 pos_lim = max_vel - |bias| 与"偏置不许反向"两条夹子后,
 *   该轮速度被压到约 max_vel - 2×C_i → 它慢下来等落后的轮子,
 *   四轮"谁领先"不再来回翻 → 甩尾与斜飘同时变小。
 * ⚠️ 只减速、【不改位置目标】→ 四轮最终仍然各自走到自己的计数目标,
 *    距离精度完全不受影响(这是它比"钳工作目标"好的地方: 后者会过冲,
 *    若把领先轮目标钳到"落后轮前方 Δ", 最多会多走 Δ≈15mm 的冤枉路)。
 * 取值:
 *   CH_SYNC_GAIN : 比例增益 (1/计数), 0 = 关闭本功能。建议 0.02~0.10。
 *      取 0.07 时"领先 ~170 计数"就吃满 CH_SYNC_MAX。
 *   CH_SYNC_MAX  : 单轮最大降速量 (计数/周期), 建议 4~12。
 *      ⚠️ 必须 < max_vel/2 (=13, 因为 pid.c 里实际降速是 2×C), 否则领先轮会被
 *         直接刹停, 反而变成"它一个人停着等"。
 *      调大 → 同步更狠、段末更不甩尾, 但整段耗时略增;
 *      调小 → 效果变弱。
 * 怎么看生效: I/HDG 的 vb 不再是严格的 "+c,-c,+c,-c" 对称值
 *   (领先轮那一侧会被额外压掉一点); 段末 {FL,BR}/{FR,BL} 的走量差应该变小。
 * 调参记录: 2026-10-01 首版 GAIN=0.05 / MAX=10 已把 626mm 右移段的
 *   "四轮完成度相位差"从 16% 压到 6.5%、段末甩尾从 −3.5° 压到 −2.6°、
 *   前向"斜飘"从 ±31mm 压到 ±10mm；本次再加到 0.07/12 想再压一半。
 * --------------------------------------------------------------------- */
#define CH_SYNC_GAIN                0.07f   /* 2026-10-01: 0.05 → 0.07 */
#define CH_SYNC_MAX                 12      /* 2026-10-01: 10 → 12 (上限别超 13!) */

